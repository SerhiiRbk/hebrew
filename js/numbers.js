  const teensFtr = ["э́сер", "ахат-эсрэ́", "штэйм-эсрэ́", "шлош-эсрэ́", "арба-эсрэ́", "хамэш-эсрэ́", "шэш-эсрэ́", "шва-эсрэ́", "шмонэ-эсрэ́", "тша-эсрэ́"];
  const teensMtr = ["асара́", "ахад-аса́р", "шнэйм-аса́р", "шлоша-аса́р", "арбаа-аса́р", "хамиша-аса́р", "шиша-аса́р", "шивъа-аса́р", "шмона-аса́р", "тишъа-аса́р"];
  const tens = ["", "", "עֶשְׂרִים", "שְׁלוֹשִׁים", "אַרְבָּעִים", "חֲמִשִּׁים", "שִׁשִּׁים", "שִׁבְעִים", "שְׁמוֹנִים", "תִּשְׁעִים"];
  const tensTr = ["", "", "эсри́м", "шлоши́м", "арбаи́м", "хамиши́м", "шиши́м", "шивъи́м", "шмони́м", "тишъи́м"];
