  const hundredsTr = ["", "мэа́", "мата́йим", "шлош мэо́т", "арба мэо́т", "хамэш мэо́т", "шэш мэо́т", "шва мэо́т", "шмонэ мэо́т", "тша мэо́т"];
  const thousands = ["", "אֶלֶף", "אַלְפַּיִם", "שְׁלוֹשֶׁת אֲלָפִים", "אַרְבַּעַת אֲלָפִים", "חֲמֵשֶׁת אֲלָפִים", "שֵׁשֶׁת אֲלָפִים", "שִׁבְעַת אֲלָפִים", "שְׁמוֹנַת אֲלָפִים", "תִּשְׁעַת אֲלָפִים"];
